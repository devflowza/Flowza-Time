import { sql } from 'kysely';
import { DAILY_REGISTER_EXPORT_MAX_ROWS, type DailyRegisterExportDto, type DailyRegisterExportInput } from '@flowza/contracts';
import { errors } from '@flowza/shared';
import type { ApiDeps } from '../../deps.js';
import { branchFilter, requirePermission } from '../../lib/authorize.js';
import { enqueueJob } from '../../lib/jobs.js';
import { likeContains, prefixTsQuery, toCount } from '../../lib/pagination.js';
import { consumeHourlyQuota } from '../../lib/quota.js';
import { type Actor, audit, runUser } from '../../lib/service.js';
import { loadSettings } from '../../lib/settings.js';
import { systemStep } from '../features/context.js';
import { dv } from '../features/sql-helpers.js';

/** Register exports per organisation per hour (each one is a report generation). */
export const REGISTER_EXPORTS_PER_HOUR = 30;

/**
 * POST /orgs/:orgId/attendance/daily/export — the daily register's CURRENT view as a spreadsheet (customer requirement
 * 2026-10-19: "search and report extraction: filtering by department and all search options, export to Excel").
 *
 * The file is a `daily_attendance` report generated by the worker (AGENTS.md rule 5: the request and its job are queued in this
 * transaction, 202 with both ids), carrying the register's filters — date, branch, department, shift, status (missing punch = the
 * MISSING_IN / MISSING_OUT flag, as the register applies it), flag and the name / number search — which the generator honours.
 * Authorisation twice: report.view + report.export + attendance.view here (the Daily Report's permissions; the file is fetched from
 * the Reports page, where the download re-checks report.export), and the caller's branch scope is written into the parameters so
 * the worker's system-context read can only narrow it. The row count the caller sees under RLS is checked against the cap and
 * audited; the per-organisation hourly quota applies. The Daily Report prints no sensitive column (identity numbers, birth dates,
 * phones, addresses), and its spreadsheets escape formula-leading text (render/csv.ts).
 */
export async function exportDailyRegister(deps: ApiDeps, actor: Actor, orgId: string, input: DailyRegisterExportInput): Promise<DailyRegisterExportDto> {
  const grant = requirePermission(actor.principal, orgId, 'report.view', 'report.export', 'attendance.view');
  const scope = branchFilter(grant, input.branchId);
  return runUser(deps.db, actor, async (trx) => {
    const settings = await loadSettings(trx, orgId);
    if (settings.security.exportRequiresReason && !input.reason) throw errors.validation('This organisation requires a reason for exports.', { issues: [{ path: 'reason', message: 'Required' }] });
    // the register's rows as the caller sees them (RLS + branch scope), less the days outside employment the file never prints
    let q = trx.selectFrom('attendanceDailyRecords as r').innerJoin('employees as e', 'e.id', 'r.employeeId')
      .where('r.organizationId', '=', orgId).where('r.attendanceDate', '=', dv(input.date)).where('r.status', 'not in', ['EXITED', 'NOT_JOINED']);
    if (scope) q = q.where('r.branchId', 'in', scope);
    if (input.departmentId) q = q.where('r.departmentId', '=', input.departmentId);
    if (input.shiftId) q = q.where('r.shiftId', '=', input.shiftId);
    if (input.status === 'MISSING_PUNCH') q = q.where(sql<boolean>`(r.status = 'MISSING_PUNCH' or r.flags && array['MISSING_IN', 'MISSING_OUT']::text[])`);
    else if (input.status) q = q.where('r.status', '=', input.status);
    if (input.flag) q = q.where(sql<boolean>`${sql.val(input.flag)} = any (r.flags)`);
    if (input.search) {
      const like = likeContains(input.search); const tsq = prefixTsQuery(input.search);
      q = q.where((eb) => eb.or([...(tsq ? [sql<boolean>`e.search @@ to_tsquery('simple', ${tsq})`] : []), eb('e.displayName', 'ilike', like), eb(sql`e.employee_number::text`, 'ilike', like)]));
    }
    const rowCount = toCount((await q.select((eb) => eb.fn.countAll().as('n')).executeTakeFirst())?.n);
    if (rowCount > DAILY_REGISTER_EXPORT_MAX_ROWS) throw errors.validation(`The export is limited to ${DAILY_REGISTER_EXPORT_MAX_ROWS} records; filter by branch or department.`, { rows: rowCount });

    // the worker runs in the organisation's system context: the caller's scope travels in the parameters (never widened)
    const parameters: Record<string, unknown> = { from: input.date };
    for (const key of ['departmentId', 'shiftId', 'status', 'flag', 'search'] as const) if (input[key]) parameters[key] = input[key];
    let branchId: string | null = input.branchId ?? null;
    if (!grant.allBranches) {
      if (!branchId) { if (grant.branchIds.length === 1) branchId = grant.branchIds[0]!; else parameters['branchIds'] = grant.branchIds; }
      parameters['branchScope'] = grant.branchIds;
    }
    if (branchId) parameters['branchId'] = branchId;
    await systemStep(trx, orgId, (t) => consumeHourlyQuota(t, orgId, 'attendance_register_exports', REGISTER_EXPORTS_PER_HOUR));
    const row = await trx.insertInto('reportRequests').values({ organizationId: orgId, reportType: 'daily_attendance', format: input.format, parameters: JSON.stringify(parameters), status: 'QUEUED', requestedBy: actor.userId, branchId })
      .returning('id').executeTakeFirstOrThrow();
    const jobId = await enqueueJob(deps.queue, trx, { queue: 'reports', jobType: 'GENERATE_REPORT', organizationId: orgId, payload: { organizationId: orgId, reportRequestId: row.id }, correlationId: actor.requestId, priority: 5 });
    await trx.updateTable('reportRequests').set({ queueJobId: jobId }).where('id', '=', row.id).execute();
    await audit(trx, actor, orgId, 'attendance.register_export_requested', 'report_request', {
      entityId: row.id, branchId, reason: input.reason ?? null,
      newValue: {
        reportType: 'daily_attendance', format: input.format, date: input.date, rowCount, jobId,
        filters: { branchId: input.branchId ?? null, departmentId: input.departmentId ?? null, shiftId: input.shiftId ?? null, status: input.status ?? null, flag: input.flag ?? null, search: input.search ?? null },
      },
    });
    return { reportId: row.id, jobId, status: 'QUEUED', reportType: 'daily_attendance', rowCount };
  });
}
